/// Vital preset JSON schema definitions and parameter allowlist.
///
/// A .vital preset file is a gzipped JSON file. This module defines:
/// - The Rust structs that map to the Vital preset schema
/// - The parameter allowlist: which keys Gemini is allowed to set, and their valid ranges
///
/// All parameter values are normalized 0.0–1.0 (per Spike C findings).
/// The Rust merge step maps to actual Vital ranges before writing the preset file.

use serde::{Deserialize, Serialize};

// ── Vital Preset Struct ───────────────────────────────────────────────────────

/// Top-level Vital preset structure.
///
/// Note: Vital's actual preset JSON format may wrap synthesis params under a
/// "settings" key. Once Nathan extracts a real Init.vital, update this struct
/// to match the actual schema if needed.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VitalPreset {
    /// Preset display name
    #[serde(default)]
    pub preset_name: String,
    /// Preset author
    #[serde(default)]
    pub author: String,
    /// Comments / description
    #[serde(default)]
    pub comments: String,
    /// Preset style tag (optional)
    #[serde(default)]
    pub preset_style: String,

    /// All synthesis parameters — flat key-value pairs merged from Init.vital.
    #[serde(flatten)]
    pub parameters: serde_json::Map<String, serde_json::Value>,
}

impl VitalPreset {
    pub fn new(name: &str) -> Self {
        Self {
            preset_name: name.to_string(),
            author: "Preset.gg".to_string(),
            comments: "Generated by Preset.gg — AI Audio-to-Preset".to_string(),
            preset_style: "".to_string(),
            parameters: serde_json::Map::new(),
        }
    }
}

