/// Look up the valid (min, max) range for a parameter name.
/// Returns None if the key is not in the allowlist (should be dropped).
pub fn find_param_range(key: &str) -> Option<(f64, f64)> {
    ALLOWED_PARAMS
        .iter()
        .find(|(k, _, _)| *k == key)
        .map(|(_, min, max)| (*min, *max))
}
